// Test 1: KnxprogImporter instantiation
void test_KnxprogImporter_Creation(void) {
    KnxprogImporter importer;
    TEST_ASSERT_TRUE(importer.getProjectName().empty());
    TEST_ASSERT_EQUAL_UINT(0, importer.getExportedDevices().size());
}

// Test 2: Manifest parsing with valid XML
void test_KnxprogImporter_ParseValidManifest(void) {
    KnxprogImporter importer;
    std::string manifest = R"(<?xml version="1.0"?>
<ManifestHeader ProjectName="TestProject" Version="1.0"/>)";
    
    TEST_ASSERT_TRUE(importer.parseManifest(manifest));
    TEST_ASSERT_EQUAL_STRING("TestProject", importer.getProjectName().c_str());
}

// Test 3: Manifest parsing with empty XML
void test_KnxprogImporter_ParseEmptyManifest(void) {
    KnxprogImporter importer;
    std::string manifest = "";
    
    // Should return false for empty manifest
    TEST_ASSERT_FALSE(importer.parseManifest(manifest));
}

// Test 4: Project import result structure
void test_KnxprogImportResult_Initialize(void) {
    KnxprogImportResult result;
    TEST_ASSERT_FALSE(result.success);
    TEST_ASSERT_EQUAL_UINT(0, result.bytesProcessed);
    TEST_ASSERT_EQUAL_UINT(0, result.totalGroupObjects);
}

// Test 5: Import from null buffer
void test_KnxprogImporter_ImportNullBuffer(void) {
    KnxprogImporter importer;
    EtsConfigLoader loader;
    
    auto result = importer.importFromBuffer(std::span<const uint8_t>{}, loader);
    TEST_ASSERT_FALSE(result.success);
    TEST_ASSERT_TRUE(result.errorMessage.length() > 0);
}

// Test 6: Import from empty buffer
void test_KnxprogImporter_ImportEmptyBuffer(void) {
    KnxprogImporter importer;
    EtsConfigLoader loader;
    uint8_t buffer[1] = {0};
    
    auto result = importer.importFromBuffer(std::span<const uint8_t>(buffer, 0), loader);
    TEST_ASSERT_FALSE(result.success);
}

// Test 7: XML tag extraction - simple case
